package com.romm.desktop.library

import com.romm.androidtv.library.LicenseNotices
import com.romm.androidtv.library.LicenseNotice

/**
 * Desktop (plain JVM) source of the aggregated open-source notices shown by the
 * "View Licenses" dialog — the desktop counterpart of Android's
 * [com.romm.androidtv.library.LicensesRepository].
 *
 * Android reads the oss-licenses-plugin raw resources (`third_party_licenses` +
 * `third_party_license_metadata`) and the vendored `assets/licenses/libretro.txt`
 * via `Context`. On a plain JVM those live on the classpath instead: the same
 * files are checked in under `desktop/src/main/resources/licenses/` and loaded
 * with [Class.getResourceAsStream].
 *
 * Parsing is delegated to the pure, shared [LicenseNotices] functions so desktop
 * and Android can never drift.
 *
 * NOTE: the two `third_party_*` files are snapshots of the oss-licenses-plugin
 * output (`app/build/generated/res/releaseOssLicensesTask/raw/`) regenerated by
 * the `releaseOssLicensesTask`/`debugOssLicensesTask` Gradle tasks. When the
 * dependency set changes, re-copy them from the app module's build output.
 */
object DesktopLicensesLoader {

    private const val METADATA_RESOURCE = "licenses/third_party_license_metadata"
    private const val LICENSES_RESOURCE = "licenses/third_party_licenses"
    private const val VENDORED_RESOURCE = "licenses/libretro.txt"

    /**
     * Loads every notice: Gradle/transitive dependencies (plugin metadata) plus the
     * vendored libretro cores. Synchronous — callers should invoke on a background
     * dispatcher (the dialog wraps this in `withContext(Dispatchers.IO)`).
     */
    fun load(): List<LicenseNotice> {
        val gradleNotices = LicenseNotices.parsePluginMetadata(
            metadata = readResource(METADATA_RESOURCE),
            licensesText = readResource(LICENSES_RESOURCE),
        )
        val vendoredNotices = LicenseNotices.parseVendored(readResource(VENDORED_RESOURCE))
        return gradleNotices + vendoredNotices
    }

    private fun readResource(path: String): String =
        DesktopLicensesLoader::class.java.classLoader
            .getResourceAsStream(path)
            ?.bufferedReader()
            ?.use { it.readText() }
            ?: error("Missing license resource on classpath: $path")
}
